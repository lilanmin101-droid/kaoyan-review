#!/usr/bin/env python3
"""english1_2024 原卷核对修正层（可重复运行；build_eng1.py 生成后自动调用）。
依据：用户逐条对照官方原卷（src/eng1/verify2024/）给出的差异。每条替换断言命中次数；已应用则跳过。
注意：Text 4 的 'teaming with aquatic life' 是原卷原文（原卷笔误），保留不改。
"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
QF, PF = f'{ROOT}/english1_2024.json', f'{ROOT}/english1_2024_passages.json'
Q, P = json.load(open(QF)), json.load(open(PF))
qid = lambda n: f'english1-2024-{n:02d}'

# (目标 id 列表, 字段, 旧, 新)；字段 'all' = 该对象所有字符串（stem/text/options），'opt:X' = 选项 X
FIX = [
    ([qid(7), qid(8), 'english1-2024-P-cloze'], 'all', 'peoples’ way', 'people’s way'),
    (['english1-2024-P-text1'], 'text', 'feature of these objects: their price', 'feature of everyday objects: their price'),
    (['english1-2024-P-text1'], 'text', 'Solar panels had few niche uses', 'Solar panels had a few niche uses'),
    ([qid(28)], 'opt:A', 'alleviates parenting pressure.', 'alleviates parenting pressures.'),
    ([qid(28)], 'opt:C', 'child-centered family', 'child-centred family'),
    ([qid(29)], 'stem', 'According to Paragraph 6, what can we learn about the nurseries in the UK?', 'What can be inferred about the nurseries in the UK?'),
    (['english1-2024-P-text2'], 'text', 'Chaudhary said that parents now have less childcare support', 'Chaudhary said that parents now had less childcare support'),
    ([qid(31)], 'opt:B', 'He is popular with the users of an AI art generator.', 'He is popular with users of an AI art generator.'),
    (['english1-2024-P-text3'], 'text', 'tracks over 10 million images and prompts generated by Stable Diffusion', 'tracks over 10 million Stable Diffusion images and prompts'),
    (['english1-2024-P-text3'], 'text', 'flooded with AI art,” Rutkowski says.', 'flooded with AI art,” Rutkowski said.'),
    ([qid(38)], 'stem', 'feel about future of the Chesapeake Bay', 'feel about the future of the Chesapeake Bay'),
    ([qid(40)], 'opt:A', 'the influence of landowners.', 'the influence of land owners.'),
    ([qid(42), 'english1-2024-P-partb'], 'all', 'is 2000 years old', 'is 2,000 years old'),
    ([qid(44), 'english1-2024-P-partb'], 'all', 'Nothing is absolutely safe, nowhere.', 'Nothing is absolutely safe nowhere.'),
    ([qid(45), 'english1-2024-P-partb'], 'all', 'cities in the US and Britain', 'cities in the U.S. and Britain'),
    ([qid(45), 'english1-2024-P-partb'], 'all', 'I would ask you to consider: why do you think', 'I would ask you to consider why do you think'),
    # 参考译文修正（用户审阅 reviews/explanations_english1_2024.jsonl）
    ([qid(48)], 'ans', '其中一种可能的解释是，它们仅靠眼睛来寻觅它们要试吃的植物，但这种情况可能会浪费大量的时间和精力，尤其是因为它们的视力实际上并不怎么好。',
     '一种可能是，它们只是用眼睛看，然后尝试吃找到的植物，但这样很可能会浪费大量的时间和精力，尤其是因为它们的视力实际上并不怎么好。'),
    ([qid(50)], 'ans', '大象完全可以用嗅觉', '大象很可能用嗅觉'),
    ([qid(50)], 'ans', '适宜食用的树丛，并评估每片树丛', '适宜食用的树丛，其次用来评估每片树丛'),
]
objs = {o['id']: o for o in Q + P}
changed = {}
def fields(o, f):
    if f == 'all': return [(o, 'stem'), (o, 'text')] + [(x, 'content') for x in o.get('options', [])]
    if f == 'ans': return [(o['answer'], j) for j in range(len(o['answer']))]
    if f.startswith('opt:'): return [(x, 'content') for x in o['options'] if x['key'] == f[4:]]
    return [(o, f)]
for ids, f, old, new in FIX:
    for i in ids:
        o = objs[i]; hit = done = 0
        for c, k in fields(o, f):
            v = c[k] if isinstance(c, list) else c.get(k)
            if not isinstance(v, str): continue
            if old in v: c[k] = v.replace(old, new); hit += v.count(old)
            elif new in v: done += 1
        assert hit or done, f'{i}: 找不到「{old}」也没有「{new}」'
        if hit: changed.setdefault(i, []).append(f'{old} → {new}')

# Text 3 分段：'Other artists … fighting back.' 独立成段；'Karla Ortiz … privacy problems.' 合为一段
t3 = objs['english1-2024-P-text3']; paras = t3['text'].split('\n\n')
k = next(j for j, x in enumerate(paras) if x.startswith('Other artists besides Rutkowski'))
if ' Karla Ortiz,' in paras[k]:
    a, b = paras[k].split(' Karla Ortiz,', 1)
    assert a.endswith('fighting back.') and paras[k + 1].endswith('privacy problems.')
    paras[k:k + 2] = [a, 'Karla Ortiz,' + b + ' ' + paras[k + 1]]
    t3['text'] = '\n\n'.join(paras); changed.setdefault(t3['id'], []).append('分段：Other artists…fighting back. 独立；Karla Ortiz…privacy problems. 合并')
else:
    assert paras[k].endswith('fighting back.') and paras[k + 1].startswith('Karla Ortiz,') and paras[k + 1].endswith('privacy problems.')

assert 'teaming with aquatic life' in objs['english1-2024-P-text4']['text']   # 原卷原文，保留
if changed:
    json.dump(Q, open(QF, 'w'), ensure_ascii=False, indent=2); json.dump(P, open(PF, 'w'), ensure_ascii=False, indent=2)
for i, c in changed.items(): print(i, *c, sep='\n  ')
print('fix_english1_2024:', '已应用' if changed else '无改动（已应用过）', len(changed), '个对象')
